// JSX를 빌드 시점에 미리 컴파일 → 실행 시 Babel 변환 제거(즉시 시작)
const Babel = require('../src/vendor/babel.min.js');
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const ORDER = [
  'store.js',
  'seed.js',
  'icons.jsx',
  'screens/home.jsx',
  'screens/entry.jsx',
  'screens/invoice.jsx',
  'screens/customers.jsx',
  'screens/inventory.jsx',
  'screens/schedule.jsx',
  'screens/stats.jsx',
  'screens/settings.jsx',
  'app.jsx',
];

const parts = [];
for (const rel of ORDER) {
  const file = path.join(SRC, rel);
  const code = fs.readFileSync(file, 'utf8');
  const out = Babel.transform(code, {
    presets: [['react', { runtime: 'classic' }]],
    filename: rel,
  }).code;
  parts.push(`/* ===== ${rel} ===== */\n${out}\n//# sourceURL=saeipari/${rel}\n`);
}

const banner = '/* AUTO-GENERATED by scripts/build-renderer.js — do not edit. */\n';
fs.writeFileSync(path.join(SRC, 'app.bundle.js'), banner + parts.join('\n'), 'utf8');
console.log('wrote src/app.bundle.js (' + ORDER.length + ' modules, ' +
  fs.statSync(path.join(SRC, 'app.bundle.js')).size + ' bytes)');
